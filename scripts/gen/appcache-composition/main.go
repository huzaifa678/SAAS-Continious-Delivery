// Generates the XAppCache Crossplane composition. Same philosophy as the
// appdatabase generator: the YAML is a build artifact, never hand-edited. The
// composing logic lives in the custom Go function (functions/function-appcache),
// which branches on the claim's mode — so this is a single, minimal composition.
//
// Usage:
//
//	go run . -out ../../../platform/compositions/appcache.yaml
package main

import (
	"flag"
	"fmt"
	"os"

	"sigs.k8s.io/yaml"
)

const (
	compositionName   = "appcache.platform.saas.example"
	fnInputAPIVersion = "appcache.fn.saas.example/v1beta1"
	providerConfig    = "aws-elasticache"
	defaultUserGroup  = "saas-redis"
)

const banner = `# ─────────────────────────────────────────────────────────────────────────────
# GENERATED by scripts/gen/appcache-composition (go run ./scripts/gen/...).
# Modern Crossplane function-pipeline Composition — do not edit by hand.
# Change the generator and re-run 'make composition'.
# ─────────────────────────────────────────────────────────────────────────────
`

// --- Composition (apiextensions.crossplane.io/v1), Pipeline mode ------------

type composition struct {
	APIVersion string          `json:"apiVersion"`
	Kind       string          `json:"kind"`
	Metadata   metadata        `json:"metadata"`
	Spec       compositionSpec `json:"spec"`
}

type metadata struct {
	Name   string            `json:"name"`
	Labels map[string]string `json:"labels,omitempty"`
}

type compositionSpec struct {
	CompositeTypeRef                  typeRef        `json:"compositeTypeRef"`
	Mode                              string         `json:"mode"`
	WriteConnectionSecretsToNamespace string         `json:"writeConnectionSecretsToNamespace,omitempty"`
	Pipeline                          []pipelineStep `json:"pipeline"`
}

type typeRef struct {
	APIVersion string `json:"apiVersion"`
	Kind       string `json:"kind"`
}

type pipelineStep struct {
	Step        string      `json:"step"`
	FunctionRef functionRef `json:"functionRef"`
	Input       any         `json:"input,omitempty"`
}

type functionRef struct {
	Name string `json:"name"`
}

type appcacheInput struct {
	APIVersion         string `json:"apiVersion"`
	Kind               string `json:"kind"`
	ProviderConfigName string `json:"providerConfigName"`
	DefaultUserGroupID string `json:"defaultUserGroupId"`
}

func build() composition {
	return composition{
		APIVersion: "apiextensions.crossplane.io/v1",
		Kind:       "Composition",
		Metadata: metadata{
			Name:   compositionName,
			Labels: map[string]string{"provider": "aws", "type": "appcache"},
		},
		Spec: compositionSpec{
			CompositeTypeRef: typeRef{
				APIVersion: "platform.saas.example/v1alpha1",
				Kind:       "XAppCache",
			},
			Mode:                              "Pipeline",
			WriteConnectionSecretsToNamespace: "crossplane-system",
			Pipeline: []pipelineStep{
				{
					// Our custom Go function composes the ElastiCache resources,
					// branching on spec.parameters.mode (shared | dedicated).
					Step:        "appcache",
					FunctionRef: functionRef{Name: "function-appcache"},
					Input: appcacheInput{
						APIVersion:         fnInputAPIVersion,
						Kind:               "Input",
						ProviderConfigName: providerConfig,
						DefaultUserGroupID: defaultUserGroup,
					},
				},
				{
					// Derives XR/claim readiness from the composed resources.
					Step:        "ready",
					FunctionRef: functionRef{Name: "function-auto-ready"},
				},
			},
		},
	}
}

func main() {
	out := flag.String("out", "", "output file (default: stdout)")
	flag.Parse()

	doc, err := yaml.Marshal(build())
	if err != nil {
		fmt.Fprintln(os.Stderr, "marshal:", err)
		os.Exit(1)
	}
	content := banner + "---\n" + string(doc)

	if *out == "" {
		fmt.Print(content)
		return
	}
	if err := os.WriteFile(*out, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "rendered composition -> %s\n", *out)
}
